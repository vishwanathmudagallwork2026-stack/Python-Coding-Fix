"""Copy prepared replacements into a local clone of the Python-coding repo.

Usage from the extracted bundle directory:
    python apply_fixes.py /path/to/Python-coding

This script updates only the listed files, adds documentation/configuration,
and removes the known temporary runner and generated bytecode file if present.
Make a backup or commit local changes before running it.
"""

from pathlib import Path
import shutil
import sys

BUNDLE_ROOT = Path(__file__).resolve().parent

# Files that are stored at the same relative path in the bundle and repository.
DIRECT_FILES = [
    "README.md",
    ".gitignore",
    "Python Basics/calculator.py",
    "Python Basics/Assignment.py",
    "Python Basics/ifelif.py",
    "Python Basics/strings.py",
    "Practice/calender.py",
    "Python/eval_func.py",
    "Python/input_function.py",
    "Python/parsing.py",
    "Python Basics/variables.py",
    "Python Basics/loops.py",
    "30June2026/if_elif.py",
    "6July2026/list.py",
    "8July2026/nested.py",
    "15July2026/funct.py",
    "8July2026/matchcase-nested_if.py",
    "24July2026/deco.py",
    "15July2026/packing.py",
    "14July2026/function2.py",
]

# Corrected lesson files exported with underscore names to avoid accidental
# overwrites when browsing the bundle; map them to their original locations.
RENAMED_SOURCES = {
    "8July2026_nested_dict.py": "8July2026/nested_dict.py",
    "8July2026_new.py": "8July2026/new.py",
    "22July2026_new1.py": "22July2026/new1.py",
    "21July2026_nestedfun.py": "21July2026/nestedfun.py",
    "23July2026_decorators.py": "23July2026/decorators.py",
    "17July2026_Pass_all_arg.py": "17July2026/Pass_all_arg.py",
}


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__)
        return 2

    repo_root = Path(sys.argv[1]).expanduser().resolve()
    if not repo_root.is_dir() or not (repo_root / ".git").exists():
        print(f"Error: {repo_root} is not a Git repository directory.")
        return 2

    missing = [name for name in DIRECT_FILES if not (BUNDLE_ROOT / name).is_file()]
    missing += [name for name in RENAMED_SOURCES if not (BUNDLE_ROOT / name).is_file()]
    if missing:
        print("Error: missing bundled files:", ", ".join(missing))
        return 2

    copied = []
    for name in DIRECT_FILES:
        source = BUNDLE_ROOT / name
        destination = repo_root / name
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, destination)
        copied.append(name)

    for source_name, destination_name in RENAMED_SOURCES.items():
        destination = repo_root / destination_name
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(BUNDLE_ROOT / source_name, destination)
        copied.append(destination_name)

    # These are generated or editor-temporary files, not learning examples.
    generated = [
        "14July2026/tempCodeRunnerFile.py",
        "Practice/__pycache__/calender.cpython-314.pyc",
    ]
    removed = []
    for name in generated:
        path = repo_root / name
        if path.is_file():
            path.unlink()
            removed.append(name)

    print(f"Updated {len(copied)} files:")
    for name in copied:
        print(f"  updated {name}")
    if removed:
        print("Removed generated/temporary files:")
        for name in removed:
            print(f"  removed {name}")
    print("Review changes with `git diff` and run the examples/tests before committing.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
